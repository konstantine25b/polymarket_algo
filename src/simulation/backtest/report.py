"""Writes RESULTS.md: model calibration vs the market, and old-style vs 'light' strategy distributions (train / test, several count lags)."""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from src.simulation.backtest.data import CACHE                  # noqa: E402
from src.simulation.backtest.sim import Strat, evaluate, prep   # noqa: E402

LIGHT = Strat(w=1.0, top_k=2, min_p=0.10, min_edge=0.02, min_ask=0.02, max_adds=0, start_after_h=96, sell_below=None)
OLD = Strat(w=1.0, top_k=99, min_p=0.08, min_edge=0.01, min_ask=0.03, max_adds=999, sell_below=0.04, max_bucket_frac=9, max_event_frac=9)
TABLES = [("zero lag (perfect real-time count)", "table.pkl"), ("count 1 h behind, lag-corrected", "table_lag1_stale6_corr.pkl"),
          ("count 2 h behind, lag-corrected", "table_lag2_stale6_corr.pkl"), ("count 3 h behind, lag-corrected", "table_lag3_stale6_corr.pkl")]


def line(lab, r):
    return f"| {lab} | {r['n']} | {r['mean']:+.2f} | {r['median']:+.2f} | {r['worst']:+.1f} | {r['win_rate']:.0%} | {r['bad_weeks']:.0%} | {r['buys']} |"


def main():
    out = ["# Backtest results (generated by `python -m src.simulation.backtest.report`)", "",
           "One fresh $40 bankroll per weekly market, $1 stakes (fee included), ask = mid + 1pt, taker fee 5% x p(1-p) on every trade,",
           "hourly decisions. 'Old rules' = the original rules (random pick, averaging down, sell < 4%, no caps) fed with the same light-model",
           "probabilities, so the comparison isolates the trading rules. Train = first 2/3 of markets (Sep 2025 - Jul 2026), test = last 1/3 (Jul - Nov 2026);",
           "the light rules were chosen on the TRAIN markets with the 2 h-lag table only.", "",
           "| rules / data | markets | mean $/wk | median | worst | weeks > 0 | weeks losing > 50% | buys |", "|---|---|---|---|---|---|---|---|"]
    for tname, f in TABLES:
        evs = prep(pd.read_pickle(CACHE / f))
        cut = len(evs) * 2 // 3
        for part, ev in (("train", evs[:cut]), ("TEST", evs[cut:])):
            out.append(line(f"light, {tname}, {part}", evaluate(ev, LIGHT)))
    evs = prep(pd.read_pickle(CACHE / "table.pkl"))
    cut = len(evs) * 2 // 3
    for part, ev in (("train", evs[:cut]), ("TEST", evs[cut:])):
        out.append(line(f"OLD rules, zero lag, {part}", evaluate(ev, OLD)))
    evs = prep(pd.read_pickle(CACHE / "table_lag2_stale6_corr.pkl"))
    for part, ev in (("train", evs[:cut]), ("TEST", evs[cut:])):
        out.append(line(f"OLD rules, 2 h lag, {part}", evaluate(ev, OLD)))
    open(Path(__file__).parent / "RESULTS.md", "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
